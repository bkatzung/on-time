# On Time - portable dev environment bootstrapper (Windows)
#
# Installs a self-contained JDK 17 + Android SDK command-line tools into
# .\.tools (gitignored) so this repo can be built/tested on ANY Windows
# machine without a system-wide Android Studio install. Also bootstraps
# the Gradle wrapper on first run.
#
# Usage (from repo root, in PowerShell):
#   .\scripts\setup-dev-env.ps1
#
# Override the install location with $env:ANDROID_DEV_HOME if desired.

$ErrorActionPreference = "Stop"

$ScriptDir = Split-Path -Parent $MyInvocation.MyCommand.Path
$ProjectRoot = Split-Path -Parent $ScriptDir
$ToolsDir = if ($env:ANDROID_DEV_HOME) { $env:ANDROID_DEV_HOME } else { Join-Path $ProjectRoot ".tools" }

$JdkDir = Join-Path $ToolsDir "jdk-17"
$SdkDir = Join-Path $ToolsDir "sdk"
$CmdlineToolsVersion = "11076708" # update if Google deprecates this build
$GradleVersion = "8.7"
$PlatformApi = "34"
$BuildToolsVersion = "34.0.0"

function Log($msg) { Write-Host "`n[setup-dev-env] $msg" }

function Install-Jdk {
    $javaExe = Join-Path $JdkDir "bin\java.exe"
    if (Test-Path $javaExe) {
        Log "JDK 17 already present at $JdkDir"
        return
    }
    Log "Downloading Temurin JDK 17 (windows/x64)..."
    $tmpZip = Join-Path $ToolsDir "jdk17.zip"
    $tmpExtract = "$JdkDir.tmp"
    New-Item -ItemType Directory -Force -Path $tmpExtract | Out-Null
    Invoke-WebRequest -Uri "https://api.adoptium.net/v3/binary/latest/17/ga/windows/x64/jdk/hotspot/normal/eclipse" -OutFile $tmpZip
    Expand-Archive -Path $tmpZip -DestinationPath $tmpExtract -Force
    Remove-Item $tmpZip
    $extracted = Get-ChildItem -Path $tmpExtract -Directory | Select-Object -First 1
    Move-Item $extracted.FullName $JdkDir
    Remove-Item $tmpExtract -Recurse -Force
    Log "JDK 17 installed to $JdkDir"
}

function Install-AndroidSdk {
    $env:ANDROID_HOME = $SdkDir
    $env:ANDROID_SDK_ROOT = $SdkDir
    $env:JAVA_HOME = $JdkDir
    $env:Path = "$JdkDir\bin;$env:Path"

    $sdkmanager = Join-Path $SdkDir "cmdline-tools\latest\bin\sdkmanager.bat"
    if (Test-Path $sdkmanager) {
        Log "Android cmdline-tools already present at $SdkDir"
    } else {
        Log "Downloading Android cmdline-tools..."
        New-Item -ItemType Directory -Force -Path (Join-Path $SdkDir "cmdline-tools") | Out-Null
        $zip = Join-Path $ToolsDir "cmdline-tools.zip"
        Invoke-WebRequest -Uri "https://dl.google.com/android/repository/commandlinetools-win-${CmdlineToolsVersion}_latest.zip" -OutFile $zip
        Expand-Archive -Path $zip -DestinationPath (Join-Path $SdkDir "cmdline-tools") -Force
        Remove-Item $zip
        Rename-Item (Join-Path $SdkDir "cmdline-tools\cmdline-tools") "latest"
    }

    Log "Accepting SDK licenses..."
    $licenses = "y`n" * 20
    $licenses | & $sdkmanager --sdk_root="$SdkDir" --licenses | Out-Null

    Log "Installing platform-tools, platform;android-$PlatformApi, build-tools;$BuildToolsVersion..."
    & $sdkmanager --sdk_root="$SdkDir" "platform-tools" "platforms;android-$PlatformApi" "build-tools;$BuildToolsVersion" | Out-Null

    Log "Android SDK ready at $SdkDir"
}

function Bootstrap-GradleWrapper {
    $gradlewBat = Join-Path $ProjectRoot "gradlew.bat"
    if (Test-Path $gradlewBat) {
        Log "Gradle wrapper already present, skipping bootstrap."
        return
    }
    Log "Bootstrapping Gradle wrapper (one-time, downloads Gradle $GradleVersion)..."
    $gdir = Join-Path $ToolsDir "gradle-bootstrap"
    $gradleExe = Join-Path $gdir "gradle-$GradleVersion\bin\gradle.bat"
    if (-not (Test-Path $gradleExe)) {
        New-Item -ItemType Directory -Force -Path $gdir | Out-Null
        $zip = Join-Path $ToolsDir "gradle-bin.zip"
        Invoke-WebRequest -Uri "https://services.gradle.org/distributions/gradle-$GradleVersion-bin.zip" -OutFile $zip
        Expand-Archive -Path $zip -DestinationPath $gdir -Force
        Remove-Item $zip
    }
    Push-Location $ProjectRoot
    try {
        $env:JAVA_HOME = $JdkDir
        & $gradleExe wrapper --gradle-version $GradleVersion --distribution-type bin
    } finally {
        Pop-Location
    }
    Log "Gradle wrapper created (gradlew.bat / gradlew)."
}

function Write-EnvFile {
    $envFile = Join-Path $ScriptDir "env.ps1"
    @"
# Generated by setup-dev-env.ps1 — dot-source this in new shells:
#   . .\scripts\env.ps1
`$env:JAVA_HOME = "$JdkDir"
`$env:ANDROID_HOME = "$SdkDir"
`$env:ANDROID_SDK_ROOT = "$SdkDir"
`$env:Path = "$JdkDir\bin;$SdkDir\platform-tools;$SdkDir\cmdline-tools\latest\bin;`$env:Path"
"@ | Set-Content -Path $envFile
    Log "Wrote $envFile — run '. .\scripts\env.ps1' in each new terminal (adds java/adb to PATH)."
}

function Write-LocalProperties {
    $lp = Join-Path $ProjectRoot "local.properties"
    if (-not (Test-Path $lp)) {
        $sdkDirForward = $SdkDir -replace '\\', '/'
        "sdk.dir=$sdkDirForward" | Set-Content -Path $lp
        Log "Wrote local.properties with sdk.dir=$sdkDirForward"
    }
}

New-Item -ItemType Directory -Force -Path $ToolsDir | Out-Null
Install-Jdk
Install-AndroidSdk
Write-LocalProperties
Bootstrap-GradleWrapper
Write-EnvFile

Log "Done. Verify with:"
Write-Host "  . .\scripts\env.ps1"
Write-Host "  java -version"
Write-Host "  adb version"
Write-Host "  .\gradlew.bat tasks"
