#!/usr/bin/env bash
# On Time - portable dev environment bootstrapper (Linux / macOS)
#
# Installs a self-contained JDK 17 + Android SDK command-line tools into
# ./.tools (gitignored) so this repo can be built/tested on ANY Linux or
# macOS machine without a system-wide Android Studio install. Also
# bootstraps the Gradle wrapper on first run.
#
# Usage:
#   ./scripts/setup-dev-env.sh
#
# Override the install location with ANDROID_DEV_HOME if desired.
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
PROJECT_ROOT="$(cd "$SCRIPT_DIR/.." && pwd)"
TOOLS_DIR="${ANDROID_DEV_HOME:-$PROJECT_ROOT/.tools}"

JDK_DIR="$TOOLS_DIR/jdk-17"
SDK_DIR="$TOOLS_DIR/sdk"
CMDLINE_TOOLS_VERSION="11076708" # update if Google deprecates this build
GRADLE_VERSION="8.7"
PLATFORM_API="34"
BUILD_TOOLS_VERSION="34.0.0"

log() { printf '\n[setup-dev-env] %s\n' "$1"; }

detect_platform() {
  case "$(uname -s)" in
    Linux*) OS_TAG="linux" ;;
    Darwin*) OS_TAG="mac" ;;
    *) echo "Unsupported OS: $(uname -s)" >&2; exit 1 ;;
  esac
  case "$(uname -m)" in
    x86_64|amd64) ARCH_TAG="x64" ;;
    arm64|aarch64) ARCH_TAG="aarch64" ;;
    *) echo "Unsupported arch: $(uname -m)" >&2; exit 1 ;;
  esac
}

require_cmd() {
  command -v "$1" >/dev/null 2>&1 || { echo "Missing required command: $1" >&2; exit 1; }
}

install_jdk() {
  if [ -x "$JDK_DIR/bin/java" ]; then
    log "JDK 17 already present at $JDK_DIR"
    return
  fi
  log "Downloading Temurin JDK 17 ($OS_TAG/$ARCH_TAG)..."
  mkdir -p "$JDK_DIR.tmp"
  local url="https://api.adoptium.net/v3/binary/latest/17/ga/${OS_TAG}/${ARCH_TAG}/jdk/hotspot/normal/eclipse"
  curl -fL "$url" -o "$TOOLS_DIR/jdk17.tar.gz"
  tar -xzf "$TOOLS_DIR/jdk17.tar.gz" -C "$JDK_DIR.tmp"
  rm -f "$TOOLS_DIR/jdk17.tar.gz"
  # Extracted dir is named like jdk-17.0.20+8 ; normalize to $JDK_DIR
  local extracted
  extracted="$(find "$JDK_DIR.tmp" -maxdepth 1 -mindepth 1 -type d | head -n1)"
  mv "$extracted" "$JDK_DIR"
  rmdir "$JDK_DIR.tmp"
  log "JDK 17 installed to $JDK_DIR"
}

install_android_sdk() {
  export ANDROID_HOME="$SDK_DIR"
  export ANDROID_SDK_ROOT="$SDK_DIR"
  export JAVA_HOME="$JDK_DIR"
  export PATH="$JAVA_HOME/bin:$PATH"

  if [ -x "$SDK_DIR/cmdline-tools/latest/bin/sdkmanager" ]; then
    log "Android cmdline-tools already present at $SDK_DIR"
  else
    log "Downloading Android cmdline-tools..."
    local zip_os="$OS_TAG"
    mkdir -p "$SDK_DIR/cmdline-tools"
    curl -fL "https://dl.google.com/android/repository/commandlinetools-${zip_os}-${CMDLINE_TOOLS_VERSION}_latest.zip" \
      -o "$TOOLS_DIR/cmdline-tools.zip"
    unzip -q -o "$TOOLS_DIR/cmdline-tools.zip" -d "$SDK_DIR/cmdline-tools"
    # Google ships it as cmdline-tools/cmdline-tools ; sdkmanager requires .../cmdline-tools/latest/...
    mv "$SDK_DIR/cmdline-tools/cmdline-tools" "$SDK_DIR/cmdline-tools/latest"
    rm -f "$TOOLS_DIR/cmdline-tools.zip"
  fi

  local sdkmanager="$SDK_DIR/cmdline-tools/latest/bin/sdkmanager"
  log "Accepting SDK licenses..."
  yes | "$sdkmanager" --sdk_root="$SDK_DIR" --licenses >/dev/null 2>&1 || true

  log "Installing platform-tools, platform;android-$PLATFORM_API, build-tools;$BUILD_TOOLS_VERSION..."
  "$sdkmanager" --sdk_root="$SDK_DIR" \
    "platform-tools" \
    "platforms;android-${PLATFORM_API}" \
    "build-tools;${BUILD_TOOLS_VERSION}" >/dev/null

  log "Android SDK ready at $SDK_DIR"
}

bootstrap_gradle_wrapper() {
  if [ -x "$PROJECT_ROOT/gradlew" ]; then
    log "Gradle wrapper already present, skipping bootstrap."
    return
  fi
  log "Bootstrapping Gradle wrapper (one-time, downloads Gradle $GRADLE_VERSION)..."
  local gdir="$TOOLS_DIR/gradle-bootstrap"
  if [ ! -x "$gdir/gradle-${GRADLE_VERSION}/bin/gradle" ]; then
    mkdir -p "$gdir"
    curl -fL "https://services.gradle.org/distributions/gradle-${GRADLE_VERSION}-bin.zip" \
      -o "$TOOLS_DIR/gradle-bin.zip"
    unzip -q -o "$TOOLS_DIR/gradle-bin.zip" -d "$gdir"
    rm -f "$TOOLS_DIR/gradle-bin.zip"
  fi
  (
    cd "$PROJECT_ROOT"
    JAVA_HOME="$JDK_DIR" "$gdir/gradle-${GRADLE_VERSION}/bin/gradle" \
      wrapper --gradle-version "$GRADLE_VERSION" --distribution-type bin
  )
  log "Gradle wrapper created (gradlew / gradlew.bat)."
}

write_env_file() {
  local envfile="$SCRIPT_DIR/env.sh"
  cat > "$envfile" <<EOF
# Generated by setup-dev-env.sh — source this in new shells:
#   source scripts/env.sh
export JAVA_HOME="$JDK_DIR"
export ANDROID_HOME="$SDK_DIR"
export ANDROID_SDK_ROOT="$SDK_DIR"
export PATH="\$JAVA_HOME/bin:\$ANDROID_HOME/platform-tools:\$ANDROID_HOME/emulator:\$ANDROID_HOME/cmdline-tools/latest/bin:\$PATH"
EOF
  log "Wrote $envfile — run 'source scripts/env.sh' in each new terminal (adds java/adb to PATH)."
}

write_local_properties() {
  local lp="$PROJECT_ROOT/local.properties"
  if [ ! -f "$lp" ]; then
    echo "sdk.dir=$SDK_DIR" > "$lp"
    log "Wrote local.properties with sdk.dir=$SDK_DIR"
  fi
}

main() {
  require_cmd curl
  require_cmd unzip
  require_cmd tar
  mkdir -p "$TOOLS_DIR"
  detect_platform
  install_jdk
  install_android_sdk
  write_local_properties
  bootstrap_gradle_wrapper
  write_env_file

  log "Done. Verify with:"
  echo "  source scripts/env.sh"
  echo "  java -version"
  echo "  adb version"
  echo "  ./gradlew tasks"
}

main "$@"
